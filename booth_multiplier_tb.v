`timescale 1ns / 1ps

//////////////////////////////////////////////////////////////////////////////////
// Testbench for booth_multiplier
//////////////////////////////////////////////////////////////////////////////////

module booth_multiplier_tb;

    // Inputs
    reg clk;
    reg reset;
    reg en;
    reg signed [15:0] A;
    reg signed [15:0] B;

    // Output
    wire signed [31:0] product;

    // Instantiate the DUT
    booth_multiplier uut (
        .clk(clk),
        .reset(reset),
        .en(en),
        .A(A),
        .B(B),
        .product(product)
    );

    ////////////////////////////////////////////////////////////
    // Clock generation (10ns period)
    ////////////////////////////////////////////////////////////
    always #5 clk = ~clk;

    ////////////////////////////////////////////////////////////
    // Test sequence
    ////////////////////////////////////////////////////////////
    initial begin

        // Initialize
        clk = 0;
        reset = 1;
        en = 0;
        A = 0;
        B = 0;

        // Hold reset
        #20;
        reset = 0;

        /////////////////////////////////////////////
        // Test 1 : 5 * 3
        /////////////////////////////////////////////
        #10;
        en = 1;
        A = 16'sd5;
        B = 16'sd3;

        #10;
        en = 0;

        /////////////////////////////////////////////
        // Test 2 : -7 * 4
        /////////////////////////////////////////////
        #20;
        en = 1;
        A = -16'sd7;
        B = 16'sd4;

        #10;
        en = 0;

        /////////////////////////////////////////////
        // Test 3 : -8 * -6
        /////////////////////////////////////////////
        #20;
        en = 1;
        A = -16'sd8;
        B = -16'sd6;

        #10;
        en = 0;

        /////////////////////////////////////////////
        // Test 4 : 123 * 45
        /////////////////////////////////////////////
        #20;
        en = 1;
        A = 16'sd123;
        B = 16'sd45;

        #10;
        en = 0;

        /////////////////////////////////////////////
        // Test 5 : large numbers
        /////////////////////////////////////////////
        #20;
        en = 1;
        A = 16'sd30000;
        B = -16'sd2;

        #10;
        en = 0;

        /////////////////////////////////////////////
        // Finish simulation
        /////////////////////////////////////////////
        #50;
        $stop;

    end

endmodule