module data_path_mac_single (
    input         clk,
    input         rst,
    input  [4:0]  rd,

    // Branch / special control
    input         beq_control,
    input         bne_control,
    input         bgeq_control,
    input         blt_control,
    input         mem_to_reg,
    input         auipc_control,
    input         jalr_control,
    input         jal_control,

    // RV32I ALU control
    input  [5:0]  ex_alu_control,
    input         ex_reg_write,

    // RV32M unit control (from ID/EX pipeline register)
    input         m_ext_enable,
    input  [2:0]  m_ext_op,

    // MAC unit control (from ID/EX pipeline register)
    input         mac_enable,
    input  [2:0]  mac_operation,

    // ID/EX pipeline values
    input  [31:0] ex_pc,
    input  [31:0] ex_rs1_val,
    input  [31:0] ex_rs2_val,
    input  [31:0] ex_imm_i,
    input  [31:0] ex_imm_u,
    input  [31:0] ex_imm_b,
    input  [31:0] ex_imm_j,
    input  [31:0] ex_imm_s,

    // Forwarding control
    input  [1:0]  forwardA,
    input  [1:0]  forwardB,

    // Forwarding data sources
    input  [31:0] ex_mem_alu_result,
    input  [31:0] mem_wb_write_data,

    // Unused external mem port (kept for compatibility)
    input  [31:0] mem_read_data_in,

    // Outputs
    output        beq,
    output        bneq,
    output        bge,
    output        blt,
    output [31:0] alu_result,      // final selected result (ALU / M-ext / MAC)
    output [31:0] next_pc,
    output [31:0] store_data,
    output [31:0] pc_plus4,

    // MAC debug
    output [31:0] mac_accum_debug,
    output        mac_overflow_debug
);

// ???????????????????????????????????????????????????????????
// PC arithmetic
// ???????????????????????????????????????????????????????????
assign pc_plus4 = ex_pc + 32'd4;

// ???????????????????????????????????????????????????????????
// Store data = forwarded rs2 (always register value)
// ???????????????????????????????????????????????????????????
assign store_data =
    (forwardB == 2'b10) ? ex_mem_alu_result :
    (forwardB == 2'b01) ? mem_wb_write_data :
                          ex_rs2_val;

// ???????????????????????????????????????????????????????????
// Forwarding: rs1 (used by ALU, M-ext, and MAC)
// ???????????????????????????????????????????????????????????
reg [31:0] rs1_fwd;
always @(*) begin
    case (forwardA)
        2'b10:   rs1_fwd = ex_mem_alu_result;
        2'b01:   rs1_fwd = mem_wb_write_data;
        default: rs1_fwd = ex_rs1_val;
    endcase
end

// ???????????????????????????????????????????????????????????
// Forwarding: rs2 register value (used by R-type, M-ext, MAC)
// ???????????????????????????????????????????????????????????
reg [31:0] rs2_fwd;
always @(*) begin
    case (forwardB)
        2'b10:   rs2_fwd = ex_mem_alu_result;
        2'b01:   rs2_fwd = mem_wb_write_data;
        default: rs2_fwd = ex_rs2_val;
    endcase
end

// ???????????????????????????????????????????????????????????
// ALU src2 mux: immediate for I-type / load / store,
//              register (forwarded) for R-type / M-ext / branch
// ???????????????????????????????????????????????????????????
reg [31:0] alu_src2_mux;
always @(*) begin
    case (ex_alu_control)
        // I-type immediates
        6'b001011, 6'b001100, 6'b001101, 6'b001110,
        6'b001111, 6'b001000, 6'b010000, 6'b010001, 6'b010010,
        // Load/Store address
        6'b010011, 6'b010100, 6'b010101, 6'b010110, 6'b010111,
        6'b011000, 6'b011001, 6'b011010:
            alu_src2_mux = ex_imm_i;
        default:
            alu_src2_mux = rs2_fwd;
    endcase
end

// AUIPC overrides both sources
wire [31:0] alu_src1 = auipc_control ? ex_pc        : rs1_fwd;
wire [31:0] alu_src2 = auipc_control ? ex_imm_u     : alu_src2_mux;

// ???????????????????????????????????????????????????????????
// JAL / JALR targets
// ???????????????????????????????????????????????????????????
wire [31:0] jal_target  = ex_pc + ex_imm_j;
wire [31:0] jalr_target = (rs1_fwd + ex_imm_i) & 32'hFFFF_FFFE;

// ???????????????????????????????????????????????????????????
// Unit 1: RV32I ALU
// ???????????????????????????????????????????????????????????
wire [31:0] alu_result_std;

alu alu_unit (
    .src1       (alu_src1),
    .src2       (alu_src2),
    .alu_control(ex_alu_control),
    .imm_val_r  (ex_imm_i),
    .shamt      (ex_imm_i[3:0]),
    .result     (alu_result_std)
);

// ???????????????????????????????????????????????????????????
// Unit 2: RV32M Multiply / Divide / Remainder
// Receives the same forwarded rs1/rs2 as the ALU.
// Enabled only when m_ext_enable=1 (power gating).
// ???????????????????????????????????????????????????????????
wire [31:0] mext_result;

rv32m_unit mext_unit (
    .m_ext_enable (m_ext_enable),
    .m_ext_op     (m_ext_op),
    .rs1          (rs1_fwd),
    .rs2          (rs2_fwd),
    .result       (mext_result)
);

// ???????????????????????????????????????????????????????????
// Unit 3: Custom MAC (16×16 Booth, with accumulator)
// Lower 16 bits of forwarded operands fed into MAC.
// Enabled only when mac_enable=1 (power gating).
// ???????????????????????????????????????????????????????????
wire [31:0] mac_result;

mac_wrapper_single mac_wrap (
    .clk           (clk),
    .rst_n         (~rst),
    .mac_enable    (mac_enable),
    .mac_operation (mac_operation),
    .operand_a     (rs1_fwd[15:0]),
    .operand_b     (rs2_fwd[15:0]),
    .mac_result    (mac_result),
    .mac_accum_out (mac_accum_debug),
    .mac_overflow  (mac_overflow_debug)
);

// ???????????????????????????????????????????????????????????
// Result mux - priority: MAC > M-ext > ALU
//   Only one unit is active at a time (mutually exclusive controls)
//   so the priority ordering is just for safety.
// ???????????????????????????????????????????????????????????
assign alu_result =
    mac_enable    ? mac_result   :
    m_ext_enable  ? mext_result  :
                    alu_result_std;

// ???????????????????????????????????????????????????????????
// Branch decisions - always from RV32I ALU (never from M-ext/MAC)
// ???????????????????????????????????????????????????????????
assign beq  = (alu_result_std == 32'd1) & beq_control;
assign bneq = (alu_result_std == 32'd1) & bne_control;
assign bge  = (alu_result_std == 32'd1) & bgeq_control;
assign blt  = (alu_result_std == 32'd1) & blt_control;

// ???????????????????????????????????????????????????????????
// Next PC
// ???????????????????????????????????????????????????????????
reg [31:0] next_pc_reg;
always @(*) begin
    if      (jal_control)       next_pc_reg = jal_target;
    else if (jalr_control)      next_pc_reg = jalr_target;
    else if (beq|bneq|bge|blt) next_pc_reg = ex_pc + ex_imm_b;
    else                        next_pc_reg = pc_plus4;
end
assign next_pc = next_pc_reg;

endmodule
