module top_riscv_mac_single (
    input  clk,
    input  reset,

    // External memory interface (MMIO / simulation probe)
    output [31:0] mem_address,
    output [31:0] mem_write_data,
    output        mem_write_enable,
    output        mem_read_enable,
    input  [31:0] mem_read_data_in,

    // Debug
    output [31:0] current_pc,
    output [31:0] instruction,
    output [4:0]  rs1, rs2, rd,
    output [6:0]  funct7, opcode,
    output [2:0]  funct3,
    output [31:0] imm_i, imm_s, imm_b, imm_u, imm_j,
    output [31:0] alu_result,
    output [31:0] write_back_data,
    output [31:0] store_data,
    output [31:0] next_pc,
    output        beq, bneq, bge, blt,
    output [1:0]  forwardA_debug, forwardB_debug,
    output        load_use_hazard_debug,

    // MAC debug
    output [31:0] mac_accumulator,
    output        mac_overflow
);

// ???????????????????????????????????????????????????????????
// ID/EX PIPELINE REGISTER
// ???????????????????????????????????????????????????????????
reg [31:0] id_ex_pc;
reg [31:0] id_ex_rs1_val, id_ex_rs2_val;
reg [31:0] id_ex_imm_i, id_ex_imm_u, id_ex_imm_b, id_ex_imm_j, id_ex_imm_s;
reg [5:0]  id_ex_alu_control;
reg        id_ex_reg_write;
reg [4:0]  id_ex_rd;
reg        id_ex_mem_read, id_ex_mem_write, id_ex_mem_to_reg;
reg        id_ex_auipc, id_ex_jalr, id_ex_jal, id_ex_lui;
// Branch controls - MUST be pipeline-registered (EX stage, not raw ID)
reg        id_ex_beq, id_ex_bne, id_ex_bge, id_ex_blt;
reg [4:0]  id_ex_rs1, id_ex_rs2;
reg [2:0]  id_ex_funct3;

// RV32M pipeline regs
reg        id_ex_m_ext_enable;
reg [2:0]  id_ex_m_ext_op;

// MAC pipeline regs
reg        id_ex_mac_enable;
reg [2:0]  id_ex_mac_operation;

// ???????????????????????????????????????????????????????????
// EX/MEM PIPELINE REGISTER
// ???????????????????????????????????????????????????????????
reg [31:0] ex_mem_alu_result, ex_mem_store_data;
reg [4:0]  ex_mem_rd;
reg [31:0] ex_mem_imm_u;
reg        ex_mem_mem_to_reg, ex_mem_mem_read, ex_mem_mem_write, ex_mem_reg_write;
reg [31:0] ex_mem_pc_plus4;
reg        ex_mem_jal, ex_mem_jalr, ex_mem_lui;
reg [2:0]  ex_mem_funct3;

// ???????????????????????????????????????????????????????????
// MEM/WB PIPELINE REGISTER
// ???????????????????????????????????????????????????????????
reg [31:0] mem_wb_alu_result, mem_wb_mem_data;
reg [4:0]  mem_wb_rd;
reg [31:0] mem_wb_imm_u;
reg        mem_wb_mem_to_reg, mem_wb_reg_write;
reg [31:0] mem_wb_pc_plus4;
reg        mem_wb_jal, mem_wb_jalr, mem_wb_lui;

// External memory pins
assign mem_address      = ex_mem_alu_result;
assign mem_write_data   = ex_mem_store_data;
assign mem_write_enable = ex_mem_mem_write;
assign mem_read_enable  = ex_mem_mem_read;

wire [31:0] wb_write_data;

// ???????????????????????????????????????????????????????????
// CONTROL UNIT WIRES
// ???????????????????????????????????????????????????????????
wire [5:0] alu_control;
wire lb, mem_to_reg, bneq_ctrl, beq_ctrl, bgeq_ctrl, blt_ctrl;
wire sw, lui_ctrl, reg_write, auipc_ctrl, jalr_ctrl, jal_ctrl;
wire        m_ext_enable_w;
wire [2:0]  m_ext_op_w;
wire        mac_enable_w;
wire [2:0]  mac_operation_w;
wire [31:0] pc_plus4;
wire        load_use_hazard;
wire        branch_taken;

// ???????????????????????????????????????????????????????????
// IF: PROGRAM COUNTER
// ???????????????????????????????????????????????????????????
reg [31:0] pc;
assign current_pc = pc;

always @(posedge clk or posedge reset) begin
    if (reset)                pc <= 32'd0;
    else if (load_use_hazard) pc <= pc;
    else                      pc <= next_pc;
end

// ???????????????????????????????????????????????????????????
// INSTRUCTION FETCH
// ???????????????????????????????????????????????????????????
instruction_memory imem (
    .clk             (clk),
    .pc              (pc),
    .reset           (reset),
    .instruction_code(instruction)
);

// ???????????????????????????????????????????????????????????
// IF/ID PIPELINE REGISTER
// ???????????????????????????????????????????????????????????
reg [31:0] instruction_code, pc_decode;

always @(posedge clk or posedge reset) begin
    if (reset) begin
        instruction_code <= 32'd0;
        pc_decode        <= 32'd0;
    end else if (branch_taken) begin
        instruction_code <= 32'd0;  // flush
        pc_decode        <= 32'd0;
    end else if (load_use_hazard) begin
        // stall: hold
        instruction_code <= instruction_code;
        pc_decode        <= pc_decode;
    end else begin
        instruction_code <= instruction;
        pc_decode        <= pc;
    end
end

// ???????????????????????????????????????????????????????????
// ID: DECODE
// ???????????????????????????????????????????????????????????
assign opcode = instruction_code[6:0];
assign rd     = instruction_code[11:7];
assign funct3 = instruction_code[14:12];
assign rs1    = instruction_code[19:15];
assign rs2    = instruction_code[24:20];
assign funct7 = instruction_code[31:25];

assign imm_i = {{20{instruction_code[31]}}, instruction_code[31:20]};
assign imm_s = {{20{instruction_code[31]}}, instruction_code[31:25], instruction_code[11:7]};
assign imm_b = {{19{instruction_code[31]}}, instruction_code[31], instruction_code[7],
                instruction_code[30:25], instruction_code[11:8], 1'b0};
assign imm_u = {instruction_code[31:12], 12'b0};
assign imm_j = {{11{instruction_code[31]}}, instruction_code[31],
                instruction_code[19:12], instruction_code[20],
                instruction_code[30:21], 1'b0};

// ???????????????????????????????????????????????????????????
// REGISTER FILE
// ???????????????????????????????????????????????????????????
wire [31:0] reg_data1, reg_data2;

register_file rf (
    .clk          (clk),
    .rst          (reset),
    .read_reg_num1(rs1),
    .read_reg_num2(rs2),
    .write_reg_num(mem_wb_rd),
    .write_data   (wb_write_data),
    .reg_write    (mem_wb_reg_write),
    .read_data1   (reg_data1),
    .read_data2   (reg_data2)
);

// ???????????????????????????????????????????????????????????
// CONTROL UNIT (RV32I + RV32M + MAC)
// ???????????????????????????????????????????????????????????
control_unit_mac_single cu (
    .reset        (reset),
    .opcode       (opcode),
    .funct3       (funct3),
    .funct7       (funct7),
    .alu_control  (alu_control),
    .lb           (lb),
    .mem_to_reg   (mem_to_reg),
    .sw           (sw),
    .lui_control  (lui_ctrl),
    .reg_write    (reg_write),
    .beq_control  (beq_ctrl),
    .bneq_control (bneq_ctrl),
    .bgeq_control (bgeq_ctrl),
    .blt_control  (blt_ctrl),
    .auipc_control(auipc_ctrl),
    .jalr_control (jalr_ctrl),
    .jal_control  (jal_ctrl),
    // RV32M
    .m_ext_enable (m_ext_enable_w),
    .m_ext_op     (m_ext_op_w),
    // MAC
    .mac_enable   (mac_enable_w),
    .mac_operation(mac_operation_w)
);

// ???????????????????????????????????????????????????????????
// ID/EX PIPELINE LATCH
// ???????????????????????????????????????????????????????????
always @(posedge clk or posedge reset) begin
    if (reset || branch_taken || load_use_hazard) begin
        // Insert bubble / flush
        id_ex_pc           <= 0; id_ex_rs1_val   <= 0; id_ex_rs2_val   <= 0;
        id_ex_imm_i        <= 0; id_ex_imm_u     <= 0; id_ex_imm_b     <= 0;
        id_ex_imm_j        <= 0; id_ex_imm_s     <= 0;
        id_ex_alu_control  <= 0; id_ex_reg_write <= 0; id_ex_rd        <= 0;
        id_ex_mem_read     <= 0; id_ex_mem_write <= 0; id_ex_mem_to_reg<= 0;
        id_ex_rs1          <= 0; id_ex_rs2       <= 0;
        id_ex_auipc        <= 0; id_ex_jalr      <= 0; id_ex_jal       <= 0;
        id_ex_lui          <= 0; id_ex_funct3    <= 0;
        id_ex_beq          <= 0; id_ex_bne       <= 0;
        id_ex_bge          <= 0; id_ex_blt       <= 0;
        id_ex_m_ext_enable <= 0; id_ex_m_ext_op  <= 0;
        id_ex_mac_enable   <= 0; id_ex_mac_operation <= 0;
    end else begin
        id_ex_pc           <= pc_decode;   id_ex_rs1_val    <= reg_data1;
        id_ex_rs2_val      <= reg_data2;   id_ex_imm_i      <= imm_i;
        id_ex_imm_u        <= imm_u;       id_ex_imm_s      <= imm_s;
        id_ex_imm_b        <= imm_b;       id_ex_imm_j      <= imm_j;
        id_ex_alu_control  <= alu_control; id_ex_reg_write  <= reg_write;
        id_ex_rd           <= rd;          id_ex_mem_read   <= lb;
        id_ex_mem_write    <= sw;          id_ex_mem_to_reg <= mem_to_reg;
        id_ex_rs1          <= rs1;         id_ex_rs2        <= rs2;
        id_ex_auipc        <= auipc_ctrl;  id_ex_jalr       <= jalr_ctrl;
        id_ex_jal          <= jal_ctrl;    id_ex_lui        <= lui_ctrl;
        id_ex_funct3       <= funct3;
        // Branch controls latched here - consumed by EX datapath next cycle
        id_ex_beq          <= beq_ctrl;
        id_ex_bne          <= bneq_ctrl;
        id_ex_bge          <= bgeq_ctrl;
        id_ex_blt          <= blt_ctrl;
        id_ex_m_ext_enable <= m_ext_enable_w;
        id_ex_m_ext_op     <= m_ext_op_w;
        id_ex_mac_enable   <= mac_enable_w;
        id_ex_mac_operation<= mac_operation_w;
    end
end

// ???????????????????????????????????????????????????????????
// FORWARDING UNIT
// ???????????????????????????????????????????????????????????
reg [1:0] forwardA, forwardB;

always @(*) begin
    forwardA = 2'b00;
    if (ex_mem_reg_write && ex_mem_rd != 0 && ex_mem_rd == id_ex_rs1)
        forwardA = 2'b10;
    else if (mem_wb_reg_write && mem_wb_rd != 0 && mem_wb_rd == id_ex_rs1)
        forwardA = 2'b01;
end

always @(*) begin
    forwardB = 2'b00;
    if (ex_mem_reg_write && ex_mem_rd != 0 && ex_mem_rd == id_ex_rs2)
        forwardB = 2'b10;
    else if (mem_wb_reg_write && mem_wb_rd != 0 && mem_wb_rd == id_ex_rs2)
        forwardB = 2'b01;
end

// ???????????????????????????????????????????????????????????
// LOAD-USE HAZARD DETECTION
// ???????????????????????????????????????????????????????????
assign load_use_hazard =
    id_ex_mem_read &&
    ((id_ex_rd == rs1) || (id_ex_rd == rs2)) &&
    (id_ex_rd != 0);

// ???????????????????????????????????????????????????????????
// EX STAGE: DATAPATH (ALU + rv32m_unit + mac_wrapper)
// ???????????????????????????????????????????????????????????
data_path_mac_single dp (
    .clk              (clk),
    .rst              (reset),
    .rd               (id_ex_rd),
    .beq_control      (id_ex_beq),   // FIX: was raw beq_ctrl (ID stage, 1 cycle early)
    .bne_control      (id_ex_bne),   // FIX: was raw bneq_ctrl
    .bgeq_control     (id_ex_bge),   // FIX: was raw bgeq_ctrl
    .blt_control      (id_ex_blt),   // FIX: was raw blt_ctrl
    .mem_to_reg       (id_ex_mem_to_reg),
    .auipc_control    (id_ex_auipc),
    .jalr_control     (id_ex_jalr),
    .jal_control      (id_ex_jal),
    .ex_alu_control   (id_ex_alu_control),
    .ex_reg_write     (id_ex_reg_write),
    // RV32M
    .m_ext_enable     (id_ex_m_ext_enable),
    .m_ext_op         (id_ex_m_ext_op),
    // MAC
    .mac_enable       (id_ex_mac_enable),
    .mac_operation    (id_ex_mac_operation),
    // Pipeline values
    .ex_pc            (id_ex_pc),
    .ex_rs1_val       (id_ex_rs1_val),
    .ex_rs2_val       (id_ex_rs2_val),
    .ex_imm_i         (id_ex_imm_i),
    .ex_imm_u         (id_ex_imm_u),
    .ex_imm_b         (id_ex_imm_b),
    .ex_imm_j         (id_ex_imm_j),
    .ex_imm_s         (id_ex_imm_s),
    // Forwarding
    .forwardA         (forwardA),
    .forwardB         (forwardB),
    .ex_mem_alu_result(ex_mem_alu_result),
    .mem_wb_write_data(wb_write_data),
    .mem_read_data_in (mem_read_data_in),
    // Outputs
    .beq              (beq),
    .bneq             (bneq),
    .bge              (bge),
    .blt              (blt),
    .alu_result       (alu_result),
    .next_pc          (next_pc),
    .store_data       (store_data),
    .pc_plus4         (pc_plus4),
    .mac_accum_debug  (mac_accumulator),
    .mac_overflow_debug(mac_overflow)
);

// ???????????????????????????????????????????????????????????
// EX/MEM PIPELINE REGISTER
// ???????????????????????????????????????????????????????????
always @(posedge clk or posedge reset) begin
    if (reset || branch_taken) begin
        ex_mem_alu_result <= 0; ex_mem_store_data <= 0; ex_mem_rd       <= 0;
        ex_mem_mem_to_reg <= 0; ex_mem_mem_read   <= 0; ex_mem_mem_write<= 0;
        ex_mem_reg_write  <= 0; ex_mem_pc_plus4   <= 0;
        ex_mem_jal        <= 0; ex_mem_jalr       <= 0; ex_mem_lui      <= 0;
        ex_mem_imm_u      <= 0; ex_mem_funct3     <= 0;
    end else begin
        ex_mem_alu_result <= alu_result;      ex_mem_store_data <= store_data;
        ex_mem_rd         <= id_ex_rd;        ex_mem_mem_to_reg <= id_ex_mem_to_reg;
        ex_mem_mem_read   <= id_ex_mem_read;  ex_mem_mem_write  <= id_ex_mem_write;
        ex_mem_reg_write  <= id_ex_reg_write; ex_mem_pc_plus4   <= pc_plus4;
        ex_mem_jal        <= id_ex_jal;       ex_mem_jalr       <= id_ex_jalr;
        ex_mem_lui        <= id_ex_lui;       ex_mem_imm_u      <= id_ex_imm_u;
        ex_mem_funct3     <= id_ex_funct3;
    end
end

// ???????????????????????????????????????????????????????????
// INTEGRATED DATA MEMORY (4 KB, byte-addressed)
// ???????????????????????????????????????????????????????????
wire [31:0] dmem_read_data;

data_memory dmem (
    .clk       (clk),
    .reset     (reset),
    .address   (ex_mem_alu_result),
    .write_data(ex_mem_store_data),
    .mem_write (ex_mem_mem_write),
    .mem_read  (ex_mem_mem_read),
    .funct3    (ex_mem_funct3),
    .read_data (dmem_read_data)
);

// ???????????????????????????????????????????????????????????
// MEM/WB PIPELINE REGISTER
// ???????????????????????????????????????????????????????????
always @(posedge clk or posedge reset) begin
    if (reset) begin
        mem_wb_alu_result <= 0; mem_wb_mem_data   <= 0; mem_wb_rd       <= 0;
        mem_wb_mem_to_reg <= 0; mem_wb_reg_write  <= 0; mem_wb_pc_plus4 <= 0;
        mem_wb_jal        <= 0; mem_wb_jalr       <= 0; mem_wb_lui      <= 0;
        mem_wb_imm_u      <= 0;
    end else begin
        mem_wb_alu_result <= ex_mem_alu_result; mem_wb_mem_data  <= dmem_read_data;
        mem_wb_rd         <= ex_mem_rd;         mem_wb_mem_to_reg<= ex_mem_mem_to_reg;
        mem_wb_reg_write  <= ex_mem_reg_write;  mem_wb_pc_plus4  <= ex_mem_pc_plus4;
        mem_wb_jal        <= ex_mem_jal;        mem_wb_jalr      <= ex_mem_jalr;
        mem_wb_lui        <= ex_mem_lui;        mem_wb_imm_u     <= ex_mem_imm_u;
    end
end

// ???????????????????????????????????????????????????????????
// WRITE BACK
// ???????????????????????????????????????????????????????????
assign wb_write_data =
    (mem_wb_jal || mem_wb_jalr) ? mem_wb_pc_plus4 :
    mem_wb_lui                  ? mem_wb_imm_u     :
    mem_wb_mem_to_reg           ? mem_wb_mem_data  :
                                  mem_wb_alu_result;

assign write_back_data = wb_write_data;

// ???????????????????????????????????????????????????????????
// BRANCH TAKEN
// ???????????????????????????????????????????????????????????
// FIX: use id_ex_jal/jalr (EX stage) not raw jal_ctrl/jalr_ctrl (ID stage)
// Using raw signals caused flush one cycle too early, corrupting the instruction
// that was already in EX when the branch/jump was still in ID.
assign branch_taken = id_ex_jal | id_ex_jalr | beq | bneq | bge | blt;

assign forwardA_debug        = forwardA;
assign forwardB_debug        = forwardB;
assign load_use_hazard_debug = load_use_hazard;

endmodule